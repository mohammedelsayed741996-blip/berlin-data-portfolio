"""Data source analysis: what each export contains, how complete it is, and which formats it uses.

Writes outputs/source_profile.csv (one row per column) and docs/data_sources.md (one section per source).
"""

from __future__ import annotations

import re

import pandas as pd

from .config import OUTPUTS, ROOT
from .sources import FILES, read_raw

PATTERNS = [("date DD.MM.YYYY", r"\d{2}\.\d{2}\.\d{4}"), ("date YYYY-MM-DD", r"\d{4}-\d{2}-\d{2}"), ("month YYYY-MM", r"\d{4}-\d{2}"),
            ("number, German format", r"-?\d{1,3}(\.\d{3})*,\d+"), ("number", r"-?\d+(\.\d+)?"), ("code", r"[A-Z0-9][A-Z0-9\-]{1,15}")]

DESCRIPTIONS = {
    "erp_a_ekpo": "ERP_A purchase order lines (plants Berlin and Erfurt), SAP-style field names, semicolon separated",
    "erp_a_lfa1": "ERP_A supplier master (SAP LFA1 style)",
    "erp_b_orders": "ERP_B purchase order lines (plant Gdansk), prices in PLN",
    "erp_b_suppliers": "ERP_B supplier master",
    "goods_receipts": "Goods receipts from both ERPs, one row per received order line",
    "quality_notifications": "Quality notifications raised at incoming inspection",
    "contracts": "Framework agreements per supplier and category, maintained in a spreadsheet by category management",
    "commodity_indices": "Monthly commodity price indices in EUR per tonne (market data subscription)",
}


def detect(values: pd.Series) -> str:
    v = values[values.ne("")].head(200)
    if v.empty:
        return "empty"
    for name, pat in PATTERNS:
        if v.map(lambda x: bool(re.fullmatch(pat, x))).mean() > 0.95:
            return name
    return "text"


def profile(raw: dict[str, pd.DataFrame] | None = None) -> pd.DataFrame:
    raw = raw or read_raw()
    rows = []
    for name, df in raw.items():
        for col in df.columns:
            s = df[col]
            rows.append({"source": name, "file": FILES[name][0], "column": col, "rows": len(df), "filled": round(float(s.ne("").mean()), 4),
                         "distinct": int(s.nunique()), "unique": bool(s.nunique() == len(df)), "format": detect(s),
                         "example": next((x for x in s if x), "")[:40]})
    return pd.DataFrame(rows)


def write_docs(p: pd.DataFrame) -> None:
    OUTPUTS.mkdir(exist_ok=True)
    p.to_csv(OUTPUTS / "source_profile.csv", index=False)
    out = ["# Data sources", "", "Generated by `spendcube.profiling` from the raw exports. Filled = share of non-empty values.", ""]
    for src, g in p.groupby("source", sort=False):
        out += [f"## {src}", "", f"{DESCRIPTIONS[src]}. File `{g.file.iloc[0]}`, {g.rows.iloc[0]:,} rows.", "",
                "| Column | Filled | Distinct | Format | Example |", "|---|---|---|---|---|"]
        out += [f"| {r.column} | {r.filled:.1%} | {r.distinct:,} | {r.format} | {r.example} |" for r in g.itertuples()]
        out.append("")
    (ROOT / "docs" / "data_sources.md").write_text("\n".join(out))
