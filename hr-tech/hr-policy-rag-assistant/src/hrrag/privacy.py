"""Remove personal data from questions before anything is logged (GDPR: data minimisation).

Employees sometimes paste their own details into a question ("I'm E-204871, my email is ...").
The answer does not need them, and the log must not keep them. Patterns covered: email addresses,
phone numbers, IBANs, German tax IDs (11 digits), employee IDs (E-123456), dates of birth and
names introduced as "my name is" / "ich heiße". No user identifier is stored; sessions are a
random token generated by the browser.
"""

from __future__ import annotations

import re

PATTERNS = [
    ("EMAIL", re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")),
    ("IBAN", re.compile(r"\b[A-Z]{2}\d{2}(?: ?[A-Z0-9]{4}){3,7}(?: ?[A-Z0-9]{1,3})?\b")),
    ("EMPLOYEE_ID", re.compile(r"\b[Ee]-?\d{5,7}\b")),
    ("TAX_ID", re.compile(r"\b\d{11}\b")),
    ("PHONE", re.compile(r"(?<!\w)(?:\+|00)?\d[\d /-]{7,}\d\b")),
    ("DATE", re.compile(r"\b\d{1,2}[./]\d{1,2}[./]\d{2,4}\b")),
    ("NAME", re.compile(r"(?i)\b(my name is|i am|i'm|ich heiße|ich bin)\s+([A-ZÄÖÜ][a-zäöüß]+(?:\s+[A-ZÄÖÜ][a-zäöüß]+)?)")),
]


def redact(text: str) -> tuple[str, list[str]]:
    """Return the text with personal data replaced by [TYPE] tags, and the list of types found."""
    found = []
    out = text or ""
    for label, rx in PATTERNS:
        if label == "NAME":
            def repl(m):
                # only treat it as a name when it is capitalised in the original text
                if m.group(2)[0].isupper():
                    found.append(label)
                    return f"{m.group(1)} [NAME]"
                return m.group(0)
            out = rx.sub(repl, out)
            continue
        if rx.search(out):
            found.append(label)
            out = rx.sub(f"[{label}]", out)
    return out, found
